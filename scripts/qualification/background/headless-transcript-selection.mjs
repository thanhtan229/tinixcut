import assert from 'node:assert/strict';
import {createServer} from 'node:http';
import {existsSync,readFileSync,mkdtempSync,rmSync,mkdirSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve,sep} from 'node:path';
import {build} from 'vite';
import {chromium} from 'playwright';
const site=mkdtempSync(join(tmpdir(),'tinix-transcript-selection-'));let server,browser;
try {
 await build({configFile:false,root:process.cwd(),logLevel:'error',build:{outDir:site,rollupOptions:{input:resolve('scripts/qualification/background/headless-transcript-selection.html')}}});
 server=createServer((req,res)=>{const file=resolve(site,'.'+new URL(req.url,'http://localhost').pathname);if(!file.startsWith(site+sep)||!existsSync(file))return res.writeHead(404).end();res.setHeader('Content-Type',file.endsWith('.html')?'text/html':'text/javascript');res.end(readFileSync(file));});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));browser=await chromium.launch({headless:true,args:['--mute-audio']});const page=await browser.newPage();
 await page.goto(`http://127.0.0.1:${server.address().port}/scripts/qualification/background/headless-transcript-selection.html`);
 await page.getByRole('button',{name:'Load second transcript'}).click();
 await page.getByRole('checkbox',{name:'Select transcript segment 1 from other.wav'}).waitFor();
 await page.getByText('voice.wav · 0.00–1.00 s',{exact:true}).waitFor();
 await page.getByText('voice.wav · 2.00–3.00 s',{exact:true}).waitFor();
 await page.getByRole('checkbox',{name:'Select transcript segment 1 from voice.wav'}).check();
 const transcript=page.getByRole('region',{name:'Source transcript'}), actions=page.getByLabel('Transcript selection actions');
 const stickyState=await transcript.evaluate(el=>{el.scrollTop=0;const box=el.getBoundingClientRect(),bar=el.querySelector('[aria-label="Transcript selection actions"]').getBoundingClientRect();return {overflow:el.scrollHeight>el.clientHeight,top:bar.top,bottom:bar.bottom,containerTop:box.top,containerBottom:box.bottom};});
 assert.equal(stickyState.overflow,true);assert.ok(stickyState.top>=stickyState.containerTop && stickyState.bottom<=stickyState.containerBottom,'selection actions remain visible at top of long transcript');
 await transcript.evaluate(el=>{el.scrollTop=el.scrollHeight;});
 assert.equal(await actions.getByRole('button',{name:'Create rough cut track'}).isVisible(),true);
 await actions.getByRole('button',{name:'Clear selection'}).click();
 await page.getByLabel('Search source transcript').fill('chào');
 await page.getByRole('button',{name:'Select 1 visible segment from voice.wav'}).click();
 await page.getByLabel('Search source transcript').fill('ơn');
 await page.getByText(/1 selected · 1 hidden by search/).waitFor();
 await page.getByRole('button',{name:'Select 1 visible segment from voice.wav'}).click();
 await page.getByLabel('Search source transcript').clear();
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 1 from voice.wav'}).isChecked(),true);
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 2 from voice.wav'}).isChecked(),true);
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 1 from other.wav'}).isDisabled(),true);
 assert.equal(await page.getByRole('button',{name:'Select 2 visible segments from other.wav'}).isDisabled(),true);
 await page.getByLabel('Search source transcript').fill('bonjour');
 await page.getByText(/2 selected · 2 hidden by search/).waitFor();
 await page.getByText(/source: voice\.wav/).waitFor();
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 1 from other.wav'}).isDisabled(),true,'hidden selection keeps other source disabled');
 await page.getByRole('button',{name:'Clear transcript search'}).click();
 assert.equal(await page.getByLabel('Search source transcript').inputValue(),'');
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 1 from voice.wav'}).isChecked(),true);
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 2 from voice.wav'}).isChecked(),true);
 await page.getByLabel('Search source transcript').fill('bonjour');
 await page.getByRole('button',{name:'Show hidden selections'}).click();
 assert.equal(await page.getByLabel('Search source transcript').inputValue(),'');
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 1 from voice.wav'}).isChecked(),true);
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 2 from voice.wav'}).isChecked(),true);
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 1 from other.wav'}).isDisabled(),true);
 assert.equal(await page.getByRole('button',{name:'Show hidden selections'}).count(),0);
 await page.getByLabel('Search source transcript').fill('chào');
 await page.getByText(/2 selected · 1 hidden by search/).waitFor();
 await page.getByRole('button',{name:'Deselect 1 visible segment from voice.wav'}).click();
 await page.getByText(/1 selected · 1 hidden by search/).waitFor();
 assert.equal(await page.getByRole('button',{name:'Deselect 0 visible segments from voice.wav'}).isDisabled(),true);
 await page.getByLabel('Search source transcript').fill('bonjour');
 assert.equal(await page.getByRole('button',{name:'Select 1 visible segment from other.wav'}).isDisabled(),true,'hidden selection still enforces one source');
 await page.getByLabel('Search source transcript').fill('ơn');
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 2 from voice.wav'}).isChecked(),true,'hidden selection survives deselect visible');
 await page.getByLabel('Search source transcript').fill('chào');
 await page.getByRole('button',{name:'Select 1 visible segment from voice.wav'}).click();
 await page.getByRole('button',{name:'Clear selection'}).click();
 assert.equal(await page.getByRole('button',{name:'Create rough cut track'}).count(),0);
 await page.getByLabel('Search source transcript').clear();
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 2 from voice.wav'}).isChecked(),false);
 await page.getByLabel('Search source transcript').fill('bonjour');
 await page.getByRole('button',{name:'Select 1 visible segment from other.wav'}).click();
 await page.getByText(/source: other\.wav/).waitFor();
 await page.getByLabel('Search source transcript').clear();
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 1 from voice.wav'}).isDisabled(),true,'clearing allows a different source and locks the first');
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 2 from other.wav'}).isChecked(),false,'bulk selection affects only visible rows');
 await page.getByRole('button',{name:'Clear selection'}).click();
 await page.getByRole('checkbox',{name:'Select transcript segment 1 from voice.wav'}).check();
 await page.getByRole('checkbox',{name:'Select transcript segment 2 from voice.wav'}).check();
 await page.getByLabel('Search source transcript').fill('no matching transcript');
 await page.getByText('No transcript segments match this search.',{exact:true}).waitFor();
 await page.getByText(/2 selected · 2 hidden by search/).waitFor();
 const hiddenSummary=await page.getByText(/2 selected · 2 hidden by search/).textContent();assert.match(hiddenSummary,/source: voice\.wav/);
 await page.getByRole('button',{name:'Clear transcript search'}).click();
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 1 from voice.wav'}).isChecked(),true);
 assert.equal(await page.getByRole('checkbox',{name:'Select transcript segment 2 from voice.wav'}).isChecked(),true);
 await page.getByRole('button',{name:'Create rough cut track'}).click();
 await page.waitForFunction(()=>window.draft!==null);
 assert.deepEqual((await page.evaluate(()=>window.draft)).ranges,[{sourceInSeconds:0,sourceOutSeconds:1},{sourceInSeconds:2,sourceOutSeconds:3}]);
 const labels=(await page.locator('section[aria-label="Source transcript"] small').allTextContents()).filter(label=>label.startsWith('voice.wav'));
 const revealedDraft=await page.evaluate(()=>window.draft);
 assert.deepEqual(labels,['voice.wav · 0.00–1.00 s','voice.wav · 2.00–3.00 s']);
 mkdirSync('artifacts/background',{recursive:true});writeFileSync('artifacts/background/transcript-reveal-operations.json',JSON.stringify({...revealedDraft,labels,hiddenSummary},null,2));
 await page.goto(`http://127.0.0.1:${server.address().port}/scripts/qualification/background/headless-transcript-selection.html`);
 await page.getByRole('button',{name:'Select 2 visible segments from voice.wav'}).click();
 await page.getByLabel('Search source transcript').fill('chào');
 await page.getByRole('button',{name:'Deselect 1 visible segment from voice.wav'}).click();
 await page.getByText(/1 selected · 1 hidden by search/).waitFor();
 await page.getByRole('button',{name:'Create rough cut track'}).click();
 await page.waitForFunction(()=>window.draft!==null);
 const subset=await page.evaluate(()=>window.draft);
 assert.equal(subset.assetId,'source');assert.deepEqual(subset.ranges,[{sourceInSeconds:2,sourceOutSeconds:3}]);
 assert.equal(subset.operations.length,2);assert.equal(subset.operations[1].operation.payload.source_start.value,60);
 mkdirSync('artifacts/background',{recursive:true});writeFileSync('artifacts/background/transcript-selection-operations.json',JSON.stringify(subset,null,2));
 console.log('PASS: transcript selection survives search and applies all selected ranges');
} finally {if(browser)await browser.close();if(server?.listening)await new Promise(r=>server.close(r));rmSync(site,{recursive:true,force:true});}
