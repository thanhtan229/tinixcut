fn default_duration() -> RationalTime {
    RationalTime::new(90, FrameRate::FPS_30) // 3.0s @ 30fps
}

fn rich_style(font_size: f32, color: &str, weight: u16) -> TextRichStyle {
    TextRichStyle {
        font: Some(FontReference {
            family: "Roboto".to_string(),
            weight,
            style: FontStyle::Normal,
            asset_id: None,
        }),
        font_size: Some(font_size),
        layout: TextLayout::default(),
        fill: TextFill::Solid {
            color: color.to_string(),
        },
        strokes: Vec::new(),
        shadows: Vec::new(),
        background: None,
        spans: Vec::new(),
    }
}

