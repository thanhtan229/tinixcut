/// Resolves a template definition by exact ID and version from the curated catalog.
pub fn resolve_curated_definition(id: &str, version: u32) -> Option<TemplateDefinition> {
    curated_definitions()
        .into_iter()
        .find(|t| t.id == id && t.version == version)
}
